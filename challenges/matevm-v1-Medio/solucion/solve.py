# Opcodes
OP_LOAD_INPUT = 0x01
OP_XOR        = 0x02
OP_ADD        = 0x03
OP_SUB        = 0x04
OP_ROL        = 0x05
OP_ROR        = 0x06
OP_CMP        = 0x07
OP_JNZ_FAIL   = 0x08
OP_HALT_OK    = 0x09
OP_HALT_FAIL  = 0x0A

def rotate_left(val, bits):
    bits = bits % 8
    return ((val << bits) | (val >> (8 - bits))) & 0xFF

def rotate_right(val, bits):
    bits = bits % 8
    return ((val >> bits) | (val << (8 - bits))) & 0xFF

