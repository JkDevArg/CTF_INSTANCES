def decrypt_bytecode():
    key = b"matevm"
    return bytes(b ^ key[i % len(key)] for i, b in enumerate(ENCRYPTED_PROGRAM))

def solve():
    bytecode = decrypt_bytecode()
    flag_chars = {}
    
    pc = 0
    current_idx = None
    ops = []
    
    while pc + 2 < len(bytecode):
        op = bytecode[pc]
        arg1 = bytecode[pc + 1]
        pc += 3
        
        if op == OP_LOAD_INPUT:
            current_idx = arg1
            ops = []
        elif op in (OP_XOR, OP_ADD, OP_SUB, OP_ROL, OP_ROR):
            ops.append((op, arg1))
        elif op == OP_CMP:
            expected = arg1
            # Reversar operaciones
            val = expected
            for o, arg in reversed(ops):
                if o == OP_ROL:
                    val = rotate_right(val, arg)
                elif o == OP_ROR:
                    val = rotate_left(val, arg)
                elif o == OP_XOR:
                    val = val ^ arg
                elif o == OP_ADD:
                    val = (val - arg) & 0xFF
                elif o == OP_SUB:
                    val = (val + arg) & 0xFF
            flag_chars[current_idx] = chr(val)
        elif op == OP_JNZ_FAIL:
            pass
        elif op == OP_HALT_OK:
            break
            
    # Reconstruir la flag en orden
    flag_len = max(flag_chars.keys()) + 1
    flag = "".join(flag_chars.get(i, "?") for i in range(flag_len))
    print(flag)

if __name__ == "__main__":
    solve()
